def crc8(data: bytes) -> int:
    c = 0
    for b in data:
        c = CRC8_TABLE[(c ^ b) & 0xFF]
    return c & 0xFF


class LD06:
    FRAME_LEN = 47
    H0 = 0x54
    H1 = 0x2C

    def __init__(self, port: str, baud: int):
        self.ser = serial.Serial(port, baudrate=baud, timeout=0.2)

    def close(self):
        try:
            self.ser.close()
        except Exception:
            pass

    def _read_frame(self) -> bytes | None:
        # sync to header
        while True:
            b = self.ser.read(1)
            if not b:
                return None
            if b[0] != self.H0:
                continue
            b2 = self.ser.read(1)
            if not b2:
                return None
            if b2[0] != self.H1:
                continue
            rest = self.ser.read(self.FRAME_LEN - 2)
            if len(rest) != self.FRAME_LEN - 2:
                return None
            frame = bytes([self.H0, self.H1]) + rest
            if crc8(frame[:-1]) != frame[-1]:
                continue
            return frame

    def _parse_frame(self, frame: bytes) -> list[tuple[float, float]]:
        if len(frame) != self.FRAME_LEN:
            return []
        start_ang = int.from_bytes(frame[4:6], "little") / 100.0

        pts = []
        offset = 6
        for _ in range(12):
            dist_mm = int.from_bytes(frame[offset:offset+2], "little")
            intensity = frame[offset+2]
            offset += 3
            pts.append((dist_mm, intensity))

        end_ang = int.from_bytes(frame[offset:offset+2], "little") / 100.0

        ang_diff = (end_ang - start_ang)
        if ang_diff < -180:
            ang_diff += 360
        elif ang_diff > 180:
            ang_diff -= 360

        out = []
        for i, (dist_mm, _intensity) in enumerate(pts):
            a = (start_ang + ang_diff * (i / 11.0)) % 360.0
            d_m = dist_mm / 1000.0
            out.append((a, d_m))
        return out

    def read_scan(self, max_frames: int = 30) -> list[tuple[float, float]]:
        scan: list[tuple[float, float]] = []
        t0 = time.time()
        for _ in range(max_frames):
            fr = self._read_frame()
            if fr is None:
                break
            scan.extend(self._parse_frame(fr))
            if time.time() - t0 > 0.08 and len(scan) > 150:
                break
        scan.sort(key=lambda x: x[0])
        return scan


