# Header: 0x54 0x2C
# Total length: 47 bytes
# [0]  0x54
# [1]  0x2C
# [2:4] speed (uint16)
# [4:6] start_angle (uint16, 0.01 deg)
# [6:42] 12 points * 3 bytes: dist(uint16 mm) + intensity(uint8)
# [42:44] end_angle (uint16, 0.01 deg)
# [44:46] timestamp (uint16)
# [46] crc8
#
